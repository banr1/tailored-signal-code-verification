//! `sha256sum`: `#![no_main]` Rust `std` on static musl computing a crate-free FIPS 180-4 SHA-256
//! digest of `stdin` (`<hex>  -`), or with `-c <hex>` comparing against an expected digest
//! (`OK` / `FAILED` with `exit 1`; malformed digest `exit 2`).

#![no_main]

